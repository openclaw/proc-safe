import { parentPort, workerData } from "node:worker_threads";
import { readProcessIdentity, readProcessAncestry } from "../dist/identity.js";
import * as darwin from "../dist/darwin.js";
import { proveLinuxEpoch } from "./linux-epoch-proof.mjs";
import { proveAncestry } from "./ancestry-proof.mjs";
const pid = workerData?.pid ?? process.pid;
const identity = readProcessIdentity(pid);
if (readProcessAncestry(pid, { maxDepth: 1 }).chain[0]?.pid !== pid) throw new Error("Worker ancestry failed");
const ancestry = await proveAncestry();
const epochSamples = workerData?.epochExecutable ? (await proveLinuxEpoch(workerData.epochExecutable)).length : undefined;
parentPort.postMessage({ identity, epochSamples, ancestryChecks: ancestry.checks, coalition: process.platform === "darwin" ? darwin.readProcessCoalition(process.pid) : undefined });
